const listeners = new Set<() => void>();

function localeStorage(): Storage | null {
  if (typeof window === 'undefined') return null;
  try {
    return window.localStorage || null;
  } catch {
    return null;
  }
}

function isLocale(value: string | null): value is Locale {
  return value === 'tr' || value === 'en' || value === 'da';
}

export function getLocale(): Locale {
  const storage = localeStorage();
  if (!storage) return currentLocale;
  const stored = storage.getItem(LOCALE_STORAGE_KEY)
    || storage.getItem(OPERATOR_LOCALE_KEY);
  if (isLocale(stored)) currentLocale = stored;
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  const storage = localeStorage();
  if (storage) {
    storage.setItem(LOCALE_STORAGE_KEY, locale);
    storage.setItem(OPERATOR_LOCALE_KEY, locale);
  }
  listeners.forEach((listener) => listener());
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function useLocale(): Locale {
  return useSyncExternalStore(subscribeLocale, getLocale, () => DEFAULT_LOCALE);
}

export function t(key: string, locale: Locale = getLocale()): string {
  return messages[locale]?.[key] || messages[DEFAULT_LOCALE]?.[key] || key;
}
